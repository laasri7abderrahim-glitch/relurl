for (const file of ["messages/en.json", "messages/fr.json", "messages/es.json"]) {
  const content = JSON.parse(fs.readFileSync(file, "utf-8"))
  
  // Deep-merge newKeys into content.dashboard
  if (!content.dashboard) content.dashboard = {}
  
  for (const [section, keys] of Object.entries(newKeys)) {
    if (!content.dashboard[section]) content.dashboard[section] = {}
    // For fr/es, use English text as placeholder if the key doesn't exist yet
    for (const [key, value] of Object.entries(keys)) {
      if (!content.dashboard[section][key]) {
        content.dashboard[section][key] = value
      }
    }
  }
  
  fs.writeFileSync(file, JSON.stringify(content, null, 2) + "\n")
  console.log(`Updated ${file}`)
}

// Now write a helper script that each component file can use to get translation keys
fs.writeFileSync(
  "scripts/dashboard-translations-summary.txt",
  `Dashboard translations added: ${Object.values(newKeys).reduce((sum, s) => sum + Object.keys(s).length, 0)} keys across ${Object.keys(newKeys).length} sections.\n` +
    Object.entries(newKeys).map(([section, keys]) => `  dashboard.${section}: ${Object.keys(keys).length} keys`).join("\n")
)
console.log("Done!")
